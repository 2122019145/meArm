param(
  [string]$Repo = (Split-Path -Parent $PSScriptRoot),
  [string]$OutDir = $null
)
$ErrorActionPreference = 'Stop'
if (-not $OutDir) { $OutDir = Join-Path $Repo 'single\serial' }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$outFile = Join-Path $OutDir 'serial_protocol_single.h'

# 依赖顺序：常量层声明/实现 -> 串口层声明/实现。
# 这四项就是“串口通信部分”的全部代码，其它模块（反解、取放、绘图、按键、
# 摇杆、舵机驱动）只是被它调用，不并进来。
$parts = @(
  'protocol_constants.h', 'protocol_constants.cpp',
  'serial_protocol.h', 'serial_protocol.cpp'
)
# 被拼进本文件的头：它们之间的 #include 要去掉（内容已在同一文件里）。
# 其它 #include 一律保留 —— 那是本模块**对外**的真实依赖，读者需要看见。
$mergedHeaders = @('protocol_constants.h', 'serial_protocol.h')

$seenSystem = @{}
$chunks = New-Object System.Collections.Generic.List[string]
$chunks.Add('// Generated by .selfcheck/make_serial_single.ps1. Do not edit this file directly.')
$chunks.Add('//')
$chunks.Add('// 串口通信部分的单文件打包稿：把协议常量层与串口协议层按依赖顺序拼在一个文件里，')
$chunks.Add('// 方便整段阅读、拷贝给别人，或移植到别的工程。拼接顺序：')
$chunks.Add('//   1/4  protocol_constants.h    串口命令协议层常量（命令字符、轴字母、缓冲大小、波特率）')
$chunks.Add('//   2/4  protocol_constants.cpp  常量层的实现')
$chunks.Add('//   3/4  serial_protocol.h       对外接口（setup/loop 里调用的两个函数 + 主动上报）')
$chunks.Add('//   4/4  serial_protocol.cpp     实现：UART 后端、行缓冲、回复、命令分发')
$chunks.Add('//')
$chunks.Add('// 被拼接掉的只有这四个文件之间互相的 #include（protocol_constants.h /')
$chunks.Add('// serial_protocol.h）。保留下来的 #include 是本模块对**本仓库其它部分**的依赖，')
$chunks.Add('// 不在这份单文件里：')
$chunks.Add('//   <Arduino.h>                  平台头（PC 端自检用 .selfcheck/mock/Arduino.cpp 顶替）')
$chunks.Add('//   "weArm_config.h"             功能开关（WEARM_ENABLE_* / WEARM_SERIAL_* 等）')
$chunks.Add('//   "constant_and_positions.h"   轴角度落地、反解、初始位姿')
$chunks.Add('//   "move.h"                     关节写入与速率限制')
$chunks.Add('//   "servo_drive.h"              舵机脉宽驱动')
$chunks.Add('//   "pick_place.h" "draw_control.h" "button_control.h" "joystick_control.h"')
$chunks.Add('//                                取放 / 绘图 / 按键 / 摇杆的命令处理')
$chunks.Add('//')
$chunks.Add('// 因此：这份文件可以单独**编译**成一个编译单元（语法/类型层面自洽），')
$chunks.Add('// 但要链接成固件还需要上面那些模块。它不是给人 #include 的（定义与实现都在里面，')
$chunks.Add('// 被多个 TU 包含会重复定义），是“一份放一起读”的打包稿。')

function Add-Source([string]$name) {
  $path = Join-Path $Repo $name
  if (-not (Test-Path -LiteralPath $path)) { throw "missing source: $path" }
  $lines = [System.IO.File]::ReadAllLines($path, [System.Text.UTF8Encoding]::new($false))
  $kept = New-Object System.Collections.Generic.List[string]
  $dropped = 0
  foreach ($line in $lines) {
    if ($line -match '^\s*#\s*include\s+"([^"]+)"') {
      $inc = $matches[1]
      if ($mergedHeaders -contains $inc) { $dropped++; continue }
      # 保留下来的依赖只留第一次出现的地方（重复 include 虽无害，单文件稿里重复列很吵）。
      if ($seenSystem.ContainsKey($inc)) { $dropped++; continue }
      $seenSystem[$inc] = $true
      # 平台头统一写成 <> 形式（源码里有写成 "Arduino.h" 的地方）。
      if ($inc -eq 'Arduino.h') { $kept.Add('#include <Arduino.h>') } else { $kept.Add($line) }
      continue
    }
    if ($line -match '^\s*#\s*include\s+<([^>]+)>') {
      $inc = $matches[1]
      if ($seenSystem.ContainsKey($inc)) { $dropped++; continue }
      $seenSystem[$inc] = $true
      $kept.Add($line)
      continue
    }
    $kept.Add($line)
  }
  $chunks.Add("`n// ============================================================")
  $chunks.Add("// ===== $name （$($lines.Count) 行，去掉 $dropped 行重复/内部 include）")
  $chunks.Add("// ============================================================")
  foreach ($line in $kept) { $chunks.Add($line) }
}

foreach ($name in $parts) { Add-Source $name }

# LF-only：.gitattributes 声明 "* text=auto eol=lf"，与 make_single.ps1 保持一致。
$text = [string]::Join("`n", $chunks) + "`n"
[System.IO.File]::WriteAllText($outFile, $text, [System.Text.UTF8Encoding]::new($false))
$lineCount = $text.Split("`n").Length - 1
Write-Host ("generated {0} ({1} bytes, {2} lines)" -f $outFile, (Get-Item -LiteralPath $outFile).Length, $lineCount)
