/*
 * weArm_config.h -- 全局编译期配置（v1.1.0 引入）
 *
 * ============================ 为什么会有这个文件 ============================
 * Arduino Uno（ATmega328P）只有 32 KB flash（avr-size 按 32768 B 计算，
 * 其中 512 B 留给 bootloader，所以实际可用 32256 B）和 2 KB SRAM。
 * v1.0.0 把取放、四按键、绘图三大功能全部编进同一个固件，编译结果是
 * 51452 B / 2319 B，直接超限（avr-size 157% / 113%）。
 *
 * v1.1.0 先把调试日志关掉、再逐函数压缩，三功能全开降到 32842 B，
 * 但仍然差 586 B，所以那一版出厂默认关掉四按键（只留取放 + 绘图）。
 *
 * 本轮又拆掉两个大头，终于让「全功能」成为出厂默认：
 *   1) 不再用 Arduino 的 HardwareSerial：release 构建直接写 UDR0 / UCSR0A，
 *      接收走 USART_RX 中断 + 64 字节环形缓冲（见 serial_protocol.cpp 的
 *      "serial backend" 段）。只要还链接 Serial 对象，它的 vtable 就会把
 *      整个 HardwareSerial 拖进来，逐函数裁剪做不到；整块换掉省了
 *      852 B flash 和 109 B SRAM。想退回官方串口库：-DWEARM_SERIAL_ARDUINO=1。
 *   2) 自研 servo_drive（Timer1 硬件 PWM）取代 Servo 库，省 550 B。
 *
 * 三功能全开现在是 32114 B / 1457 B，离可用 flash 只剩 142 B、
 * SRAM 也到了 71% —— 已经很挤了（摇杆手感修正那一轮又花掉 202 B flash，
 * 见下面的容量表），
 * 后面再加功能之前，先用下面的容量表挑一个开关关掉，或者重新做一轮瘦身。
 *
 * 这里提供两个维度的编译期开关：
 *   1) WEARM_DEBUG_SERIAL -- 关掉全部串口调试日志（默认关）
 *   2) WEARM_ENABLE_xxx   -- 按功能裁剪（关掉的功能会被链接器完全丢弃，
 *                            既不占 flash 也不占 SRAM）
 *
 * 关闭某个功能时，该模块的头文件会退化成一组空实现的 inline 桩函数，
 * 因此**调用方（meArm.ino / serial_protocol.cpp / joystick_control.cpp /
 * button_control.cpp）一行都不用改**，编译器会把空调用直接优化掉。
 *
 * ============================== 怎么用 =====================================
 * 想改配置，**只需要改本文件里的数字**（0 = 关，1 = 开），其它文件不用动：
 *
 *   WEARM_DEBUG_SERIAL        1 -> 在串口上打印各模块的中文调试日志
 *                             （实测 +9260 B，很占 flash，排故时才开；
 *                              打开后会退回 Arduino Serial，见上面 1)）
 *   WEARM_ENABLE_PICK_PLACE   1 -> 取放序列（串口 A/B/C、按键1 循环取放）
 *   WEARM_ENABLE_BUTTONS      1 -> 按键模块（录制/播放/回中/循环取放，串口 N/R/P/M/0）
 *   WEARM_ENABLE_DRAW         1 -> 绘图（铅笔轨迹，v1.0.0 的功能）
 *   WEARM_BUTTON_PINS         0 -> 不读 D2~D5 的物理按键（默认，本机没有独立按键）
 *                             1 -> 四个独立按键接 D2~D5（INPUT_PULLUP、按下接地）
 *   WEARM_REC_TICK_MS       200 -> 录制采样周期（ms）；越小回放越顺、录得越短
 *   WEARM_REC_ENTRIES       192 -> 录制缓冲条数（× 4 字节 SRAM）＝ 单次录制上限
 *                                  （192 × 200 ms = 38.4 秒、768 B SRAM，见第 5 节）
 *
 * 三个功能开关默认都是 1（全功能）。万一以后代码又长胖到装不下，
 * 照下面的容量表关掉最不常用的那一个即可。
 *
 * 摇杆、串口协议解析、反解/限位、舵机驱动这些底层能力没有开关，永远编译进去。
 *
 * 如果要批量改动（例如 PC 端自检要打开全部功能，或做容量消融实验），
 * 可以在命令行上用 -D 覆盖，不会被本文件的默认值挡住：
 *     -DWEARM_ENABLE_PICK_PLACE=1 -DWEARM_ENABLE_BUTTONS=1 -DWEARM_ENABLE_DRAW=1
 * 注意 avr_build.ps1 的 -ExtraDefs 收的是字符串**数组**：
 *     -ExtraDefs @('-DWEARM_ENABLE_BUTTONS=1','-DWEARM_ENABLE_DRAW=1')
 * 把多个 -D 塞进一个带空格的字符串会被当成一个参数，报
 * "token "=" is not valid in preprocessor expressions"。
 *
 * 实测容量（Program / Data，**v1.6.4 定版实编**；百分比按 32768 / 2048 算）：
 *     取放 + 按键 + 绘图       : 32016 B (97.7%) / 1475 B (72.0%)  <- 出厂默认
 *     取放 + 绘图   + 按键关   : 28814 B (87.9%) /  558 B (27.2%)
 *     取放 + 按键   + 绘图关   : 19260 B (58.8%) / 1224 B (59.8%)
 *     绘图 + 按键   + 取放关   : 29114 B (88.8%) / 1441 B (70.4%)
 * 默认配置相对 Uno 可用 flash（32256 B）只剩 **240 B** 余量
 * （单文件版 32028 B / 97.7%，余量 228 B；两者差 +12 B 是 LTO 内联顺序）。
 * 本轮（删掉"偏转越大走得越快"的动态步间间隔 + 施密特迟滞 + 中位跟踪时间门控）相对上一轮
 * 【四行为 32114 / 28922 / 19280 / 29240，Data 1457 / 540 / 1206 / 1423】分别
 * **−98 / −108 / −20 / −126 B**，Data 四行 **+18 B**：删掉 `speedIntervalMs()` 与
 * `jogIntervalMs()` 两个带浮点乘除与区间夹取的插值函数省下的，比新增的迟滞判断多；
 * 改为所有移动源直接用固定的 `speed.stepDelayMs`（慢/中/快 = 80/40/20 ms），
 * 摇杆新增 `JOY_HYST 25`（静止起控 65、已起控保持 40）与 `JOY_TRACK_MS 20`
 * 时间门控，SRAM 多出 `s_axisHot[4]` + `s_trackMs[4]`（8 B，其余是布局对齐差）。
 * 上一轮（"偏转越大越快"版）四行分别 **+202 / +202 / +198 / +92 B**、Data 四行**全部不变**：
 * 花掉的是运行期中位跟踪（`readAxisAmp()` 里死区内每轮挪 1 个计数）、
 * `speedIntervalMs()` 的插值带来的乘除、以及关节步长按偏转缩放
 * （每格 `speed.stepSize × 偏转/500`，下限 `JOY_STEP_MIN_DEG 0.1` 度）。
 * **余量已经小于 1% 的 flash，再加功能必须先关一个模块。**
 * 上面四行之前是"角度语义回归 + 恢复字母N/三角形/字母Z"之后重测的（v1.6.3 的同一批
 * 行是 31656 / 28478 / 19198 / 28818，Data 1415 / 498 / 1206 / 1381）：
 * 恢复三张顶点表与三个任务名、加 drawTaskTag() 与 F 的 "OK F=<tag>" 回执，
 * 扣掉删掉串口 1/2/3 与 k/K（及其 posToolOpen/posToolClose）省下的部分，
 * 默认配置净 **+256 B flash / +42 B SRAM**，其余三行同样小幅上浮。
 * 对照 v1.1.0 的旧数字（29476 / 20126 / 30074 / 32842）看版本演进。
 * （v1.3.0 的四行是 31936 / 28534 / 19226 / 29184：摇杆中位自标定、方向镜像、
 *   录制中按 P 先收尾再播放这三个实机修复，一共让体积涨了 200~240 B；
 *   v1.4.0 默认 WEARM_BUTTON_PINS=0、不再读 D2~D5，省回 510 B flash / 28 B SRAM，
 *   删掉"录制时长必须 >10 秒"的判定又省 58 B，最终默认配置比 v1.3.0 净省 332 B。
 *   录制深度改造（录制缓冲 128 条 × 3 B -> 192 条 × 4 B、采样 100 -> 200 ms，再加 8 个
 *   double 的回放子步状态）：默认配置 +334 B flash / +420 B SRAM；含按键模块的
 *   两行同样 +286~332 B flash、+420 B SRAM；"取放 + 绘图（按键关）"那一行**完全
 *   不变**，因为 button_control.cpp 根本没参与编译。
 *   本轮把"移动到指定 x,y,z"合并成 move.cpp 的 moveToPoint() 一份实现（绘图的
 *   solveStep/tryApplyPoint/applyPointClamped 与串口的 protoMoveToCoords 全部删除）：
 *   默认 −168 B、按键关 −170 B、取放关 −224 B，Data 四行**全部不变**；只有"绘图关"
 *   那一行 +28 B —— 那个配置里绘图本来就没编进去，没有重复代码可省，而 moveToPoint()
 *   无论谁用都要编译一份，省下来的重复代码只出现在同时用到绘图的配置里。）
 *   分支 draw_control 把内置图形从 7 个裁到 4 个（删掉字母 N / 三角形 / 字母 Z 的顶点表
 *   与任务名），并把绘制运动整体放慢、加一道"单次写入位移不超过 0.02 单位"的上限
 *   （DRAW_STEP_MAX）：默认 −64 B、按键关 −52 B、取放关 −112 B，"绘图关"那一行因为
 *   绘图模块根本不参与编译而完全不变（Data 四行 +1 B）。拆开看：删表 + 减速 + 采样步长
 *   0.5→0.25 这些改动一共省 96 B，新增的"位移上限"花掉 32 B。
 *   注意这个上限本来想写成"一轮里拆成多个 0.02 的小步循环送出"，实测**同样功能要多花
 *   662 B flash**（默认配置 32336 B，超过 Uno 可用的 32256 B，根本编译不进 Uno），
 *   于是改成"这一轮最多走 0.02、剩下的下一轮补"；正常 loop 周期下两种写法行为一致
 *   （3 单位/秒 时一步只有 0.003~0.015 单位，上限不生效）。
 *   再往后是示教点动的修复（步长单位错、间隔方向写反、示教期关掉 A2 夹爪，见
 *   .selfcheck/README.md 的"修复：五点示教时摇杆控制错乱"）：把原来那段
 *   "拿角度步长当位移"的逻辑换成按偏转比例缩放的坐标步长并给 A2 加了编译期开关，
 *   反而让默认配置又小了 50 B（31706 -> 31656），Data 四行不变。
 */
#ifndef WEARM_CONFIG_H
#define WEARM_CONFIG_H

/* ---------------------------------------------------------------------------
 * 1) 串口调试日志总开关
 *    打开后 constant_and_positions / joystick_control / serial_protocol /
 *    pick_place / button_control / draw_control 六个模块都会打印日志。
 *    中文字符串按 UTF-8 每个字 3 字节，实测全开会让固件大 9260 B
 *    （42192 -> 51452）。注意 AVR 的 .rodata 是并进 .text 的，
 *    所以这些字符串只占 flash、**不占 SRAM**（v1.0.0 的注释写错了）。
 *
 *    打开这个开关还会让串口退回 Arduino 的 HardwareSerial（调试日志和
 *    协议回复要共用一条有序输出流，裸寄存器的 TX 不参与 printf 缓冲），
 *    所以排故构建的体积会明显大于 release 构建，属正常现象。
 * ------------------------------------------------------------------------ */
#ifndef WEARM_DEBUG_SERIAL
#  define WEARM_DEBUG_SERIAL 0
#endif

/* ---------------------------------------------------------------------------
 * 2) 功能裁剪开关
 * ------------------------------------------------------------------------ */

/* 取放序列：把 A/B/C 三个物体夹到各自的放置点（串口 A/B/C，按键1 循环） */
#ifndef WEARM_ENABLE_PICK_PLACE
#  define WEARM_ENABLE_PICK_PLACE 1
#endif

/* 按键模块：录制 / 播放 / 回中 / 循环取放。
 * 默认开启；触发方式默认是串口 N / R / P / M（或 0），物理引脚见第 4 节
 * 的 WEARM_BUTTON_PINS（默认 0 = 不读 D2~D5）。 */
#ifndef WEARM_ENABLE_BUTTONS
#  define WEARM_ENABLE_BUTTONS 1
#endif

/* 绘图：铅笔轨迹绘制（v1.0.0 新增，串口 F/D/G/E/Q/U/W/p/n/o） */
#ifndef WEARM_ENABLE_DRAW
#  define WEARM_ENABLE_DRAW 1
#endif

/* ---------------------------------------------------------------------------
 * 3) 机械装配方向镜像
 *    实机装配时，基座回转（通道 0 / b）与末端夹爪（通道 3 / f）的舵机是
 *    反向装上的：逻辑角增大时它们物理上朝反方向走。实机表现：
 *      - 左右旋转的舵机转向反了（摇杆/坐标指令给的方向与机械实际相反）；
 *      - 串口 O（张开 = 逻辑角 maxF）实际把爪子夹紧、S（夹紧 = minF）反而张开。
 *    修法不动 0~180 的整套映射，也不动任何逻辑角，只在唯一写出口
 *    writeServo() 里对这两个通道做一次"在自身行程窗口内镜像"：
 *        physical = (min + max) - logical
 *    逻辑角（限位、反解、录制回放、绘图、示教）仍是唯一真值，变的只是最后
 *    送给舵机的那个数。镜像后 physical 仍落在 [min,max] 区间内：
 *    b 是 [0,180] 对称、f 是 [60,150] 对称（60+150=210），所以夹爪不可能被
 *    推到机械危险区。
 *    换一套装配（舵机正着装）就把对应开关改成 0，其它文件一行都不用动。
 * ------------------------------------------------------------------------ */
#ifndef WEARM_MIRROR_BASE
#  define WEARM_MIRROR_BASE 1   /* 1 = 基座回转（通道 0 / b）反向装配，输出镜像 */
#endif
#ifndef WEARM_MIRROR_TOOL
#  define WEARM_MIRROR_TOOL 1   /* 1 = 末端夹爪（通道 3 / f）反向装配，输出镜像 */
#endif

/* ---------------------------------------------------------------------------
 * 4) 物理按键引脚开关（默认不用物理按键）
 *    本机只接了两根摇杆（A0~A3 的 X/Y）：D2~D5 上没有独立按键，曾经把
 *    KY-023 摇杆自带的按压开关（SW 脚）接到 D2 = 按键1 = 循环取放。实机问题：
 *    把**右摇杆推到最前**时机械上会压到那颗轻触开关 → 假触发一次"按键1"
 *    → 正在手动推杆的操作被 pickPlaceStart() 抢走（摇杆随即被 locked 锁住），
 *    现象就是"右摇杆向前本来该转下臂，结果触发了自动取放"。
 *
 *    所以默认 0：**完全不读 D2~D5**（连 pinMode 都不做，省下 4 路扫描与
 *    24 字节消抖状态），四个按键的全部功能改由串口字符触发：
 *        N      循环执行：夹 A -> B -> C -> A（= 原按键1）
 *        R      录制 开/关（= 原按键2）
 *        P      播放上一次录制（= 原按键3；录制中直接发 P 会先收尾再播放）
 *        M / 0  回中：平滑回到开机初始位姿（= 原按键4）
 *    改成 1 就恢复"四个独立按键接 D2~D5、INPUT_PULLUP、按下接地"的老接线。
 *
 *    注意：这个开关只裁剪"读引脚"那一段（buttonSetup/buttonLoop/btnEdge）。
 *    button_control.cpp 的录制 / 播放 / 回中 / 循环取放逻辑、上面四条串口
 *    命令、（绘图示教中的）按键语义都不受影响；WEARM_ENABLE_BUTTONS 也不必动。
 *    PC 端探针想测物理按键，在包含 button_control.cpp 之前定义 1 即可：
 *        #define WEARM_BUTTON_PINS 1
 * ------------------------------------------------------------------------ */
#ifndef WEARM_BUTTON_PINS
#  define WEARM_BUTTON_PINS 0   /* 0 = 不读 D2~D5（全部走串口），1 = 物理按键 */
#endif

/* ---------------------------------------------------------------------------
 * 5) 录制深度与采样率（SRAM 大户，改之前先把账算清楚）
 *    button_control.cpp 的录制缓冲是一块**静态** SRAM：每 WEARM_REC_TICK_MS
 *    毫秒写恰好一条 4 字节记录（四个关节各 8 位有符号增量、单位 0.5°），
 *    所以
 *        缓冲占用 = WEARM_REC_ENTRIES × 4 字节
 *        单次录制上限 = WEARM_REC_ENTRIES × WEARM_REC_TICK_MS
 *
 *    默认 192 条 × 200 ms = **38.4 秒**、768 字节（v1.4.0 之前是 128 条 ×
 *    100 ms = 12.8 秒、384 字节）。Uno 只有 2048 B SRAM，实测 Data 段因此从
 *    994 B 涨到 **1414 B（69.0%）**，留给栈还有 634 B（不含缓冲的底子是 646 B，
 *    所以可以按"646 + 条数 × 4"估）。再往上加要小心：256 条 = 1024 B，Data 会到
 *    1670 B（81.5%），栈只剩 378 B，**不建议**；320 条 = 1280 B 就到 1926 B
 *    （94%），基本没有栈空间了。
 *
 *    为什么一条记录是 4 字节（而不是老版的 3 字节 / 6 位字段）：
 *      6 位字段每关节只有 ±16°（32 单位 × 0.5°），200 ms 一条就是 80°/s ——
 *      实测摇杆推到满偏录十几秒，几乎每条记录都被削到 ±16° 顶格（探针
 *      probe_button 的 [9] 段看得到这个现象），录下来的动作是"限速"过的，
 *      回放终点也对不上。改成 8 位字段后每条约 ±64°＝317°/s，正常档
 *      （1°/10 ms = 100°/s）、中速档都录得下，不再削顶。
 *      比字段还快的极端速度（快速档最快 2°/5 ms = 400°/s）也不丢角度：超出
 *      的部分会攒进后面的记录里慢慢吐出（btnRecCollect 里的 s_snap 进位），
 *      收尾时再连续补写几条把尾巴走完（btnStopRecording），代价只是时间轴被
 *      压扁一点。
 *
 *    这几个数怎么取舍：
 *      - TICK 越小回放越顺，但同样 SRAM 能录的时间越短。200 ms 一条时回放本来
 *        是"每 200 ms 跳一步"，所以 button_control.cpp 的播放会把每条记录再拆
 *        成 4 个 50 ms 子步插值展开（BTN_PLAY_SUBSTEPS，设 1 就退回"整条一次
 *        跳完"的老行为）。录下的角度序列不变，只是走得更连续。
 *      - 想省 SRAM：96 条 × 200 ms = 19.2 秒（384 B）；想录更久：256 条 ×
 *        200 ms = 51.2 秒，但要 1024 B SRAM（Data 81.5%，栈只剩约 378 B）。
 *      - TICK 也能单独调：192 条 × 250 ms = 48 秒（还是 768 B，回放更"顿"）。
 * ------------------------------------------------------------------------ */
#ifndef WEARM_REC_TICK_MS
#  define WEARM_REC_TICK_MS 200  /* 采样周期 ms（越小回放越顺、录得越短） */
#endif
#ifndef WEARM_REC_ENTRIES
#  define WEARM_REC_ENTRIES 192  /* 记录条数（× 4 字节 = 静态 SRAM 占用） */
#endif

#endif /* WEARM_CONFIG_H */
